import AppKit

struct PasteboardSnapshot { let types: [NSPasteboard.PasteboardType]; let payload: ClipboardPayload; let sourceBundleIdentifier: String? }
protocol PasteboardClient: AnyObject { var changeCount: Int { get }; func snapshot() -> PasteboardSnapshot?; func write(_ payload: ClipboardPayload) }
final class SystemPasteboardClient: PasteboardClient {
    let pasteboard: NSPasteboard
    init(_ pasteboard: NSPasteboard = .general) { self.pasteboard = pasteboard }
    var changeCount: Int { pasteboard.changeCount }
    static func source(frontmost: String?, own: String?) -> String? { frontmost == own ? nil : frontmost }
    func snapshot() -> PasteboardSnapshot? {
        let types = pasteboard.types ?? []
        let hostile = types.map(\.rawValue).contains {
            $0.localizedCaseInsensitiveContains("concealed")
                || $0.localizedCaseInsensitiveContains("transient")
                || $0.localizedCaseInsensitiveContains("autogenerated")
                || $0.localizedCaseInsensitiveContains("password")
                || $0.localizedCaseInsensitiveContains("foundry")
        }
        guard !hostile else { return nil }
        let sourceBundle = Self.source(frontmost: NSWorkspace.shared.frontmostApplication?.bundleIdentifier, own: Bundle.main.bundleIdentifier)
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return PasteboardSnapshot(types: types, payload: .files(urls), sourceBundleIdentifier: sourceBundle)
        }
        if let value = pasteboard.string(forType: .string) ?? (pasteboard.readObjects(forClasses: [NSURL.self]) as? [URL])?.first?.absoluteString,
           !value.isEmpty {
            return PasteboardSnapshot(types: types, payload: .text(value), sourceBundleIdentifier: sourceBundle)
        }
        if let data = pasteboard.data(forType: .tiff), !data.isEmpty {
            return PasteboardSnapshot(types: types, payload: .image(data), sourceBundleIdentifier: sourceBundle)
        }
        if let data = pasteboard.data(forType: .png), !data.isEmpty {
            return PasteboardSnapshot(types: types, payload: .image(data), sourceBundleIdentifier: sourceBundle)
        }
        return nil
    }
    func write(_ payload: ClipboardPayload) {
        pasteboard.clearContents()
        switch payload {
        case .text(let value): pasteboard.setString(value, forType: .string)
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        case .image(let data): pasteboard.setData(data, forType: .tiff)
        }
    }
}

extension NSPasteboard {
    func copy(_ string: String) {
        clearContents()
        setString(string, forType: .string)
    }
}
