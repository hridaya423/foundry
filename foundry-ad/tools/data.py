"""Bundle data/*.json, the TV screen rect and the Foundry wordmark tiles into js/data.js (no fetches at render)."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
timing = json.load(open(os.path.join(ROOT, "data/timing.json")))
screen = json.load(open(os.path.join(ROOT, "assets/img/tv/screen.json")))
tiles = json.load(open(os.path.join(ROOT, "../anvil/public/assets/foundry/tile-layout.json")))
k = 1920 / screen["space"][0]
data = {
    "timing": timing,
    "screen": {key: round(screen[key] * k, 2) for key in ("x", "y", "w", "h", "radius")},
    "wordmark": {"viewBox": [1672, 510], "tiles": [{"id": t["id"], "l": t["letter"], "x": t["x"], "y": t["y"],
                 "p": [[[round(a, 2), round(b, 2)] for a, b in poly] for poly in t["polygons"]]} for t in tiles]},
}
with open(os.path.join(ROOT, "js/data.js"), "w") as f:
    f.write("// generated by tools/data.py\nwindow.FD = " + json.dumps(data, separators=(",", ":")) + ";\n")
print("js/data.js", os.path.getsize(os.path.join(ROOT, "js/data.js")), "bytes;", len(tiles), "tiles")
